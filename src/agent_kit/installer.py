"""Install the kit into a project (design §8)."""

import shutil
import subprocess
import sys
from collections import namedtuple
from pathlib import Path

from . import __version__
from .harness import DEFAULT_HARNESS, HARNESSES
from .lock import file_hash, read_lock, text_hash, write_lock

KIT_DIR = ".agents/kit"
LOCK_FILE = ".agents/kit.lock"
AGENTS = "AGENTS.md"
TEMPLATES = ("AGENTS.md", "GLOSSARY.md", "docs/agents/project.md")
GITATTRIBUTES = ".gitattributes"
GITATTRIBUTES_LINE = ".agents/kit/hooks/* text eol=lf"
GITKEEP_FOLDERS = ("docs/adr", ".scratch")

BEGIN = "<!-- agent-kit:begin -->"
END = "<!-- agent-kit:end -->"

HARNESS_SH = (
    "# Generated by agent-kit. Do not edit; run `agent-kit update` instead.\n"
    'AGENT_MARKERS="{markers}"\n'
)

BlockState = namedtuple("BlockState", ["state", "begin", "end", "reason"])


def payload_root():
    return Path(__file__).parent / "payload"


def confirm_deletion(paths, stdin, stdout):
    """Ask for a typed confirmation before --force deletes anything."""
    if not stdin.isatty():
        print(
            "Refusing --force: it needs a confirmation typed at an interactive terminal.",
            file=stdout,
        )
        return False

    print("These paths will be deleted:", file=stdout)
    for path in paths:
        print(path, file=stdout)
    stdout.write("Type 'yes' to delete them and continue: ")
    stdout.flush()
    answer = stdin.readline()
    if answer.strip() == "yes":
        return True

    print("Aborted. Nothing was changed.", file=stdout)
    return False


def find_block(text):
    """Return the state of the kit block in AGENTS.md (design §5)."""
    begins = text.count(BEGIN)
    ends = text.count(END)

    if begins == 0 and ends == 0:
        return BlockState("absent", None, None, None)

    if begins != 1 or ends != 1:
        return BlockState(
            "bad",
            None,
            None,
            "expected exactly one begin marker and one end marker, "
            f"found {begins} begin and {ends} end",
        )

    begin = text.index(BEGIN)
    end = text.index(END)
    if end < begin:
        return BlockState(
            "bad", None, None, "the end marker appears before the begin marker"
        )

    return BlockState("ok", begin, end, None)


def apply_block(text, block):
    """Return text with the kit block written between the markers."""
    content = block.replace("\r\n", "\n").rstrip("\n")
    markers = f"{BEGIN}\n{content}\n{END}"
    state = find_block(text)

    if state.state == "ok":
        return text[: state.begin] + markers + text[state.end + len(END) :]

    if state.state == "absent":
        before = text.rstrip("\n")
        if before:
            return f"{before}\n\n{markers}\n"
        return f"{markers}\n"

    raise ValueError(f"bad kit block: {state.reason}")


def init(root, harness_name, force, stdin, stdout, payload=None):
    """Install the kit into root. Return the process exit code."""
    root = Path(root).resolve()
    source = Path(payload) if payload is not None else payload_root()
    harness_name = harness_name or DEFAULT_HARNESS

    # Every check runs before anything is written.
    if not _is_git_root(root):
        print(f"{root} is not the root of a git repository.", file=sys.stderr)
        return 2

    if harness_name not in HARNESSES:
        print(
            f"Unknown harness '{harness_name}'. "
            f"Known harnesses: {', '.join(sorted(HARNESSES))}.",
            file=sys.stderr,
        )
        return 2

    if (root / LOCK_FILE).exists():
        version = "unknown"
        try:
            existing = read_lock(root)
        except ValueError:
            existing = None
        if existing is not None:
            version = existing.get("kit_version", "unknown")
        print(
            f"agent-kit is already installed (version {version}). "
            "Use `agent-kit update`.",
            file=sys.stderr,
        )
        return 2

    harness = HARNESSES[harness_name]
    kit_dir = root / KIT_DIR
    skills_dir = root / harness.skills_dir
    conflicts = _files_under(root, kit_dir) + _files_under(root, skills_dir)
    conflicts.sort()

    if conflicts:
        if not force:
            print(
                "Cannot install: these paths already exist and would be replaced:",
                file=stdout,
            )
            for path in conflicts:
                print(path, file=stdout)
            print(
                "Move them out of the way, or rerun with --force to delete them.",
                file=stdout,
            )
            return 1

        if not confirm_deletion(conflicts, stdin, stdout):
            return 1
        for folder in (kit_dir, skills_dir):
            if folder.exists():
                _remove_folder(folder)

    state = find_block(_read_text(root / AGENTS)) if (root / AGENTS).exists() else None
    if state is not None and state.state == "bad":
        print(
            "Cannot install: AGENTS.md has a broken agent-kit block: "
            f"{state.reason}.",
            file=stdout,
        )
        return 1

    # The checks are done; write the kit.
    created = []
    _copy_payload(root, source, harness, created)

    kept = []
    templates_root = source / "templates"
    for name in TEMPLATES:
        destination = root / name
        if destination.exists():
            kept.append(name)
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes((templates_root / name).read_bytes())
        created.append(name)

    block_action, block_text = _write_kit_block(root, source, AGENTS in created)

    for folder in GITKEEP_FOLDERS:
        if not (root / folder).is_dir():
            (root / folder).mkdir(parents=True, exist_ok=True)
            (root / folder / ".gitkeep").write_bytes(b"")
            created.append(f"{folder}/.gitkeep")

    _ensure_gitattributes(root, created)

    if not _set_hooks_path(root, stdout):
        return 1

    write_lock(
        root,
        __version__,
        harness.name,
        _kit_owned_hashes(root, harness),
        text_hash(block_text),
    )
    created.append(LOCK_FILE)

    _print_summary(stdout, harness.name, created, kept, block_action)
    return 0


def update(root, force, stdin, stdout, payload=None):
    """Update an installed kit. Return the process exit code."""
    root = Path(root).resolve()
    source = Path(payload) if payload is not None else payload_root()

    # Every check runs before anything is written.
    if not _is_git_root(root):
        print(f"{root} is not the root of a git repository.", file=sys.stderr)
        return 2

    try:
        existing = read_lock(root)
    except ValueError:
        existing = None
    if existing is None or not isinstance(existing.get("files"), dict):
        print(
            "agent-kit is not installed here. Use `agent-kit init`.",
            file=sys.stderr,
        )
        return 2

    harness_name = existing.get("harness")
    if harness_name not in HARNESSES:
        print(
            f"Unknown harness '{harness_name}'. "
            f"Known harnesses: {', '.join(sorted(HARNESSES))}.",
            file=sys.stderr,
        )
        return 2

    harness = HARNESSES[harness_name]
    agents_path = root / AGENTS
    agents_text = _read_text(agents_path) if agents_path.is_file() else None
    state = find_block(agents_text) if agents_text is not None else None

    changes = _local_changes(root, existing, harness, state, agents_text)
    if changes:
        if not force:
            print(
                "Cannot update: these kit-owned files were changed in this project:",
                file=stdout,
            )
            for path, reason in changes:
                print(f"  {path} ({reason})", file=stdout)
            print(
                "Kit-owned files are changed in the agent-kit repo, not in a "
                "project. Move your change there, restore the files, or rerun "
                "with --force to discard them.",
                file=stdout,
            )
            return 1

        if not confirm_deletion([path for path, _ in changes], stdin, stdout):
            return 1

    if state is not None and state.state == "bad":
        print(
            "Cannot update: AGENTS.md has a broken agent-kit block: "
            f"{state.reason}.",
            file=stdout,
        )
        return 1

    # The checks are done; replace the kit-owned folders.
    for folder in (root / KIT_DIR, root / harness.skills_dir):
        if folder.exists():
            _remove_folder(folder)

    created = []
    _copy_payload(root, source, harness, created)
    block_action, block_text = _write_kit_block(root, source)
    _ensure_gitattributes(root, created)

    if not _set_hooks_path(root, stdout):
        return 1

    files = _kit_owned_hashes(root, harness)
    write_lock(root, __version__, harness.name, files, text_hash(block_text))

    _print_update_summary(
        stdout,
        existing.get("kit_version", "unknown"),
        existing["files"],
        files,
        block_action,
    )
    return 0


def _is_git_root(root):
    try:
        result = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
        )
    except OSError:
        return False
    if result.returncode != 0 or not result.stdout.strip():
        return False
    try:
        top = Path(result.stdout.strip()).resolve()
    except OSError:
        return False
    return top == root


def _files_under(root, folder):
    """Return repo-relative POSIX paths of the files under folder."""
    if not folder.is_dir():
        if folder.is_file():
            return [folder.relative_to(root).as_posix()]
        return []
    return sorted(
        path.relative_to(root).as_posix()
        for path in folder.rglob("*")
        if path.is_file()
    )


def _remove_folder(folder):
    if folder.is_dir():
        shutil.rmtree(str(folder))
    else:
        folder.unlink()


def _local_changes(root, existing, harness, state, agents_text):
    """Return (path, reason) pairs for local changes to kit-owned files."""
    changes = []
    files = existing["files"]
    for name, digest in files.items():
        path = root / name
        if not path.is_file():
            changes.append((name, "missing"))
        elif file_hash(path) != digest:
            changes.append((name, "modified"))

    for folder in (root / KIT_DIR, root / harness.skills_dir):
        for name in _files_under(root, folder):
            if name not in files:
                changes.append((name, "not installed by agent-kit"))

    if state is None or state.state == "absent":
        changes.append((AGENTS, "kit block missing markers"))
    elif state.state == "ok":
        if text_hash(_block_text(agents_text, state)) != existing.get(
            "agents_block"
        ):
            changes.append((AGENTS, "kit block in AGENTS.md modified"))

    changes.sort()
    return changes


def _block_text(text, state):
    """Return the text the kit lock hashes: between the marker lines."""
    segment = text[state.begin + len(BEGIN) : state.end]
    if segment.startswith("\r\n"):
        return segment[2:]
    if segment.startswith("\n"):
        return segment[1:]
    return segment


def _copy_payload(root, source, harness, created):
    """Copy the payload into the project and write harness.sh."""
    source = Path(source)
    created.extend(_copy_tree(root, source / "kit", root / KIT_DIR))
    created.extend(_copy_tree(root, source / "skills", root / harness.skills_dir))

    hook = root / KIT_DIR / "hooks" / "pre-commit"
    if hook.is_file():
        hook.chmod(0o755)

    harness_file = root / KIT_DIR / "harness.sh"
    _write_text(
        harness_file,
        HARNESS_SH.format(markers=" ".join(harness.agent_markers)),
    )
    created.append(harness_file.relative_to(root).as_posix())


def _write_kit_block(root, source, agents_created=False):
    """Write the kit block; return the action and the text the lock hashes."""
    block = _read_text(Path(source) / "agents-block.md").rstrip("\n")
    agents_path = root / AGENTS
    agents_text = _read_text(agents_path) if agents_path.is_file() else ""
    state = find_block(agents_text)
    _write_text(agents_path, apply_block(agents_text, block))
    if state.state == "absent":
        action = "appended"
    elif agents_created:
        action = "filled from the template"
    else:
        action = "replaced"
    return action, block + "\n"


def _set_hooks_path(root, stdout):
    result = subprocess.run(
        ["git", "-C", str(root), "config", "core.hooksPath", ".agents/kit/hooks"],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(
            "Could not set core.hooksPath: " + result.stderr.strip(),
            file=stdout,
        )
        return False
    return True


def _kit_owned_hashes(root, harness):
    return {
        path.relative_to(root).as_posix(): file_hash(path)
        for path in _kit_owned_files(root, harness)
    }


def _copy_tree(root, source, target):
    """Copy every file from source to target; return repo-relative paths."""
    written = []
    for path in sorted(source.rglob("*")):
        if not path.is_file():
            continue
        destination = target / path.relative_to(source)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(str(path), str(destination))
        written.append(destination.relative_to(root).as_posix())
    return written


def _kit_owned_files(root, harness):
    paths = [root / KIT_DIR, root / harness.skills_dir]
    files = []
    for folder in paths:
        if folder.is_dir():
            files.extend(
                path for path in folder.rglob("*") if path.is_file()
            )
    return sorted(files)


def _ensure_gitattributes(root, created):
    path = root / GITATTRIBUTES
    line = GITATTRIBUTES_LINE.encode("utf-8")
    if not path.exists():
        path.write_bytes(line + b"\n")
        created.append(GITATTRIBUTES)
        return

    data = path.read_bytes()
    if GITATTRIBUTES_LINE in data.decode("utf-8").splitlines():
        return

    if data and not data.endswith(b"\n"):
        data += b"\n"
    path.write_bytes(data + line + b"\n")


def _read_text(path):
    return path.read_text(encoding="utf-8")


def _write_text(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _print_summary(stdout, harness_name, created, kept, block_action):
    print(
        f"Installed agent-kit {__version__} (harness: {harness_name}).",
        file=stdout,
    )
    print("", file=stdout)

    if created:
        print("Created:", file=stdout)
        for path in created:
            print(f"  {path}", file=stdout)
        print("", file=stdout)

    if kept:
        print("Kept:", file=stdout)
        for path in kept:
            print(f"  {path}", file=stdout)
        print("", file=stdout)

    print(f"Kit block: {block_action} in AGENTS.md.", file=stdout)
    print("Next: review and commit the changes.", file=stdout)


def _print_update_summary(stdout, old_version, old_files, new_files, block_action):
    print(
        f"Updated agent-kit from {old_version} to {__version__}.",
        file=stdout,
    )
    print("", file=stdout)

    updated = sorted(
        name
        for name in new_files
        if name in old_files and old_files[name] != new_files[name]
    )
    added = sorted(set(new_files) - set(old_files))
    removed = sorted(set(old_files) - set(new_files))
    for title, names in (
        ("Updated", updated),
        ("Added", added),
        ("Removed", removed),
    ):
        if not names:
            continue
        print(f"{title}:", file=stdout)
        for name in names:
            print(f"  {name}", file=stdout)
        print("", file=stdout)

    print(f"Kit block: {block_action} in AGENTS.md.", file=stdout)
    print("Next: review and commit the changes.", file=stdout)
