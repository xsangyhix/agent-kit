"""Install the kit into a project (design §8)."""

import enum
import shutil
import subprocess
import sys
from collections import namedtuple
from pathlib import Path

from . import __version__
from .harness import DEFAULT_HARNESS, HARNESSES
from .lock import LOCK_NAME, file_hash, read_lock, text_hash, write_lock

KIT_DIR = ".agents/kit"
HOOKS_DIR = KIT_DIR + "/hooks"
HOOK = HOOKS_DIR + "/pre-commit"
AGENTS = "AGENTS.md"
TEMPLATES = ("AGENTS.md", "GLOSSARY.md", "docs/agents/project.md")
GITATTRIBUTES = ".gitattributes"
GITATTRIBUTES_LINE = HOOKS_DIR + "/* text eol=lf"
GITKEEP_FOLDERS = ("docs/adr", ".scratch")

BEGIN = "<!-- agent-kit:begin -->"
END = "<!-- agent-kit:end -->"

HARNESS_SH = (
    "# Generated by agent-kit. Do not edit; run `agent-kit update` instead.\n"
    'AGENT_MARKERS="{markers}"\n'
)


class BlockKind(enum.Enum):
    ABSENT = "absent"
    BAD = "bad"
    OK = "ok"


BlockState = namedtuple("BlockState", ["state", "begin", "end", "reason"])


def payload_root():
    return Path(__file__).parent / "payload"


def _resolve_inputs(root, payload):
    """Return the resolved project root and the payload source."""
    root = Path(root).resolve()
    source = Path(payload) if payload is not None else payload_root()
    return root, source


def _require_git_root(root):
    """Refuse root unless it is a git repository root; return success."""
    if _is_git_root(root):
        return True
    print(f"{root} is not the root of a git repository.", file=sys.stderr)
    return False


def _select_harness(harness_name):
    """Return the harness, or refuse an unknown one and return None."""
    harness = HARNESSES.get(harness_name)
    if harness is not None:
        return harness
    print(
        f"Unknown harness '{harness_name}'. "
        f"Known harnesses: {', '.join(sorted(HARNESSES))}.",
        file=sys.stderr,
    )
    return None


def _refuse_broken_block(command, state, stdout):
    """Refuse a broken block; return whether it refused."""
    if state is None or state.state is not BlockKind.BAD:
        return False
    print(
        f"Cannot {command}: AGENTS.md has a broken agent-kit block: "
        f"{state.reason}.",
        file=stdout,
    )
    return True


def confirm_deletion(paths, stdin, stdout, replaces_block=False):
    """Ask for a typed confirmation before --force deletes anything.

    Only paths that update or init will really delete are listed. A changed
    or missing kit block is not a deletion, so it gets a line of its own.
    """
    if not stdin.isatty():
        print(
            "Refusing --force: it needs a confirmation typed at an interactive terminal.",
            file=stdout,
        )
        return False

    if paths:
        print("These paths will be deleted:", file=stdout)
        for path in paths:
            print(path, file=stdout)
    if replaces_block:
        print("The kit block in AGENTS.md will be replaced.", file=stdout)
    if paths:
        stdout.write("Type 'yes' to delete them and continue: ")
    else:
        stdout.write("Type 'yes' to continue: ")
    stdout.flush()
    answer = stdin.readline()
    if answer.strip() == "yes":
        return True

    print("Aborted. Nothing was changed.", file=stdout)
    return False


def find_block(text):
    """Return the state of the kit block in AGENTS.md (design §5).

    A marker counts only when it stands on a line of its own. A marker
    mentioned in prose, or indented, is ordinary text.
    """
    markers = _marker_lines(text)
    begins = [start for kind, start in markers if kind == "begin"]
    ends = [start for kind, start in markers if kind == "end"]

    if not begins and not ends:
        return BlockState(BlockKind.ABSENT, None, None, None)

    if len(begins) != 1 or len(ends) != 1:
        return BlockState(
            BlockKind.BAD,
            None,
            None,
            "expected exactly one begin marker and one end marker, "
            f"found {len(begins)} begin and {len(ends)} end",
        )

    begin = begins[0]
    end = ends[0]
    if end < begin:
        return BlockState(
            BlockKind.BAD,
            None,
            None,
            "the end marker appears before the begin marker",
        )

    return BlockState(BlockKind.OK, begin, end, None)


def _marker_lines(text):
    """Return (kind, line start) for every marker line in text."""
    markers = []
    start = 0
    while start <= len(text):
        newline = text.find("\n", start)
        content_end = len(text) if newline == -1 else newline
        line = text[start:content_end].rstrip()
        if line == BEGIN:
            markers.append(("begin", start))
        elif line == END:
            markers.append(("end", start))
        if newline == -1:
            break
        start = newline + 1
    return markers


def _line_content_end(text, start):
    """Return the end of the line's content, before its line ending."""
    newline = text.find("\n", start)
    if newline == -1:
        return len(text)
    if newline > start and text[newline - 1] == "\r":
        return newline - 1
    return newline


def _line_ending(text):
    """Return the file's newline: CRLF when its first newline is one."""
    newline = text.find("\n")
    if newline > 0 and text[newline - 1] == "\r":
        return "\r\n"
    return "\n"


def apply_block(text, block):
    """Return text with the kit block written between the markers.

    Every byte outside the markers is unchanged. The marker lines and the
    block use the file's line ending, so a CRLF file stays CRLF; a file
    whose first newline is LF (or that has none) stays LF.
    """
    newline = _line_ending(text)
    content = block.replace("\r\n", "\n").rstrip("\n").replace("\n", newline)
    markers = f"{BEGIN}{newline}{content}{newline}{END}"
    state = find_block(text)

    if state.state is BlockKind.OK:
        end = _line_content_end(text, state.end)
        return text[: state.begin] + markers + text[end:]

    if state.state is BlockKind.ABSENT:
        before = text.rstrip("\r\n")
        if before:
            return before + newline + newline + markers + newline
        return markers + newline

    raise ValueError(f"bad kit block: {state.reason}")


def init(root, harness_name, force, stdin, stdout, payload=None):
    """Install the kit into root. Return the process exit code."""
    root, source = _resolve_inputs(root, payload)
    harness_name = harness_name or DEFAULT_HARNESS

    # Every check runs before anything is written.
    if not _require_git_root(root):
        return 2

    harness = _select_harness(harness_name)
    if harness is None:
        return 2

    if (root / LOCK_NAME).exists():
        version = "unknown"
        try:
            existing = read_lock(root)
        except ValueError:
            existing = None
        if existing is not None:
            version = existing.get("kit_version", "unknown")
        print(
            f"agent-kit is already installed (version {version}). "
            "Use `agent-kit update`.",
            file=sys.stderr,
        )
        return 2

    conflicts = _kit_owned_paths(root, harness)
    agents_path = root / AGENTS
    state = find_block(_read_text(agents_path)) if agents_path.exists() else None

    if conflicts and not force:
        print(
            "Cannot install: these paths already exist and would be replaced:",
            file=stdout,
        )
        for path in conflicts:
            print(path, file=stdout)
        print(
            "Move them out of the way, or rerun with --force to delete them.",
            file=stdout,
        )
        return 1

    # The marker check runs before the deletion confirmation, so a refused run
    # neither deletes anything nor asks the user to confirm it.
    if _refuse_broken_block("install", state, stdout):
        return 1

    if conflicts:
        if not confirm_deletion(conflicts, stdin, stdout):
            return 1
        for folder in _kit_folders(root, harness):
            if folder.exists():
                _remove_folder(folder)

    # The checks are done; write the kit.
    created = []
    _copy_payload(root, source, harness, created)
    if not _record_hook_mode(root, stdout):
        return 1

    kept = []
    templates_root = source / "templates"
    for name in TEMPLATES:
        destination = root / name
        if destination.exists():
            kept.append(name)
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes((templates_root / name).read_bytes())
        created.append(name)

    block_action, block_text = _write_kit_block(root, source, AGENTS in created)

    for folder in GITKEEP_FOLDERS:
        if not (root / folder).is_dir():
            (root / folder).mkdir(parents=True, exist_ok=True)
            (root / folder / ".gitkeep").write_bytes(b"")
            created.append(f"{folder}/.gitkeep")

    _ensure_gitattributes(root, created)

    if not _set_hooks_path(root, stdout):
        return 1

    write_lock(
        root,
        __version__,
        harness.name,
        _kit_owned_hashes(root, harness),
        text_hash(block_text),
    )
    created.append(LOCK_NAME)

    _print_report(
        stdout,
        f"Installed agent-kit {__version__} (harness: {harness.name}).",
        (("Created", created), ("Kept", kept)),
        block_action,
    )
    return 0


def update(root, force, stdin, stdout, payload=None):
    """Update an installed kit. Return the process exit code."""
    root, source = _resolve_inputs(root, payload)

    # Every check runs before anything is written.
    if not _require_git_root(root):
        return 2

    try:
        existing = read_lock(root)
    except ValueError:
        existing = None
    if existing is None or not isinstance(existing.get("files"), dict):
        print(
            "agent-kit is not installed here. Use `agent-kit init`.",
            file=sys.stderr,
        )
        return 2

    harness = _select_harness(existing.get("harness"))
    if harness is None:
        return 2

    agents_path = root / AGENTS
    agents_text = _read_text(agents_path) if agents_path.is_file() else None
    state = find_block(agents_text) if agents_text is not None else None

    changes = _local_changes(root, existing, harness, state, agents_text)
    if changes and not force:
        print(
            "Cannot update: these kit-owned files were changed in this project:",
            file=stdout,
        )
        for path, reason in changes:
            print(f"  {path} ({reason})", file=stdout)
        print(
            "Kit-owned files are changed in the agent-kit repo, not in a "
            "project. Move your change there, restore the files, or rerun "
            "with --force to discard them.",
            file=stdout,
        )
        return 1

    # The marker check runs before the deletion confirmation, so a refused run
    # neither deletes anything nor asks the user to confirm it.
    if _refuse_broken_block("update", state, stdout):
        return 1

    if changes:
        deletions = [path for path, _ in changes if path != AGENTS]
        replaces_block = any(path == AGENTS for path, _ in changes)
        if not confirm_deletion(
            deletions, stdin, stdout, replaces_block=replaces_block
        ):
            return 1

    # The checks are done; replace the kit-owned folders.
    for folder in _kit_folders(root, harness):
        if folder.exists():
            _remove_folder(folder)

    created = []
    _copy_payload(root, source, harness, created)
    if not _record_hook_mode(root, stdout):
        return 1
    block_action, block_text = _write_kit_block(root, source)
    _ensure_gitattributes(root, created)

    if not _set_hooks_path(root, stdout):
        return 1

    files = _kit_owned_hashes(root, harness)
    write_lock(root, __version__, harness.name, files, text_hash(block_text))

    old_files = existing["files"]
    updated = sorted(
        name
        for name in files
        if name in old_files and old_files[name] != files[name]
    )
    _print_report(
        stdout,
        f"Updated agent-kit from {existing.get('kit_version', 'unknown')} "
        f"to {__version__}.",
        (
            ("Updated", updated),
            ("Added", sorted(set(files) - set(old_files))),
            ("Removed", sorted(set(old_files) - set(files))),
        ),
        block_action,
    )
    return 0


def _is_git_root(root):
    try:
        result = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
        )
    except OSError:
        return False
    if result.returncode != 0 or not result.stdout.strip():
        return False
    try:
        top = Path(result.stdout.strip()).resolve()
    except OSError:
        return False
    return top == root


def _files_under(root, folder):
    """Return repo-relative POSIX paths of the files under folder."""
    if not folder.is_dir():
        if folder.is_file():
            return [folder.relative_to(root).as_posix()]
        return []
    return sorted(
        path.relative_to(root).as_posix()
        for path in folder.rglob("*")
        if path.is_file()
    )


def _kit_folders(root, harness):
    """Return the two folders the kit owns."""
    return (root / KIT_DIR, root / harness.skills_dir)


def _kit_owned_paths(root, harness):
    """Return the repo-relative paths of the kit-owned folders' files."""
    return sorted(
        name
        for folder in _kit_folders(root, harness)
        for name in _files_under(root, folder)
    )


def _remove_folder(folder):
    if folder.is_dir():
        shutil.rmtree(str(folder))
    else:
        folder.unlink()


def _local_changes(root, existing, harness, state, agents_text):
    """Return (path, reason) pairs for local changes to kit-owned files."""
    changes = []
    files = existing["files"]
    for name, digest in files.items():
        path = root / name
        if not path.is_file():
            changes.append((name, "missing"))
        elif file_hash(path) != digest:
            changes.append((name, "modified"))

    for name in _kit_owned_paths(root, harness):
        if name not in files:
            changes.append((name, "not installed by agent-kit"))

    if state is None or state.state is BlockKind.ABSENT:
        changes.append((AGENTS, "kit block missing markers"))
    elif state.state is BlockKind.OK:
        if text_hash(_block_text(agents_text, state)) != existing.get(
            "agents_block"
        ):
            changes.append((AGENTS, "kit block in AGENTS.md modified"))

    changes.sort()
    return changes


def _block_text(text, state):
    """Return the text the kit lock hashes: between the marker lines."""
    newline = text.find("\n", state.begin + len(BEGIN))
    if newline == -1:
        return ""
    return text[newline + 1 : state.end]


def _copy_payload(root, source, harness, created):
    """Copy the payload into the project and write harness.sh."""
    source = Path(source)
    created.extend(_copy_tree(root, source / "kit", root / KIT_DIR))
    created.extend(_copy_tree(root, source / "skills", root / harness.skills_dir))

    hook = root / HOOK
    if hook.is_file():
        hook.chmod(0o755)

    harness_file = root / KIT_DIR / "harness.sh"
    _write_text(
        harness_file,
        HARNESS_SH.format(markers=" ".join(harness.agent_markers)),
    )
    created.append(harness_file.relative_to(root).as_posix())


def _write_kit_block(root, source, agents_created=False):
    """Write the kit block; return the action and the text the lock hashes."""
    block = _read_text(Path(source) / "agents-block.md").replace("\r\n", "\n").rstrip("\n")
    agents_path = root / AGENTS
    agents_text = _read_text(agents_path) if agents_path.is_file() else ""
    state = find_block(agents_text)
    _write_text(agents_path, apply_block(agents_text, block))
    if state.state is BlockKind.ABSENT:
        action = "appended"
    elif agents_created:
        action = "filled from the template"
    else:
        action = "replaced"
    return action, block + "\n"


def _set_hooks_path(root, stdout):
    result = subprocess.run(
        ["git", "-C", str(root), "config", "core.hooksPath", HOOKS_DIR],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(
            "Could not set core.hooksPath: " + result.stderr.strip(),
            file=stdout,
        )
        return False
    return True


def _record_hook_mode(root, stdout):
    """Record the installed hook's executable bit in the git index.

    `core.filemode` is false on Windows, so git would record a new hook as
    100644 and a POSIX clone would silently skip it. This is the one index
    change the tool makes; it never stages anything else or commits.
    """
    result = subprocess.run(
        [
            "git",
            "-C",
            str(root),
            "update-index",
            "--add",
            "--chmod=+x",
            HOOK,
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(
            "Could not record the hook's executable bit in the git index: "
            + result.stderr.strip(),
            file=stdout,
        )
        return False
    return True


def _kit_owned_hashes(root, harness):
    return {
        name: file_hash(root / name)
        for name in _kit_owned_paths(root, harness)
    }


def _copy_tree(root, source, target):
    """Copy every file from source to target; return repo-relative paths."""
    written = []
    for path in sorted(source.rglob("*")):
        if not path.is_file():
            continue
        if path.suffix == ".pyc" or "__pycache__" in path.parts:
            continue
        destination = target / path.relative_to(source)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(str(path), str(destination))
        written.append(destination.relative_to(root).as_posix())
    return written


def _ensure_gitattributes(root, created):
    path = root / GITATTRIBUTES
    line = GITATTRIBUTES_LINE.encode("utf-8")
    if not path.exists():
        path.write_bytes(line + b"\n")
        created.append(GITATTRIBUTES)
        return

    data = path.read_bytes()
    if GITATTRIBUTES_LINE in data.decode("utf-8").splitlines():
        return

    if data and not data.endswith(b"\n"):
        data += b"\n"
    path.write_bytes(data + line + b"\n")


def _read_text(path):
    """Read text without translating CRLF to LF (design §8)."""
    return path.read_bytes().decode("utf-8")


def _write_text(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _print_report(stdout, headline, sections, block_action):
    """Print a summary with titled lists and the common footer."""
    print(headline, file=stdout)
    print("", file=stdout)

    for title, names in sections:
        if not names:
            continue
        print(f"{title}:", file=stdout)
        for name in names:
            print(f"  {name}", file=stdout)
        print("", file=stdout)

    print(f"Kit block: {block_action} in AGENTS.md.", file=stdout)
    print("Next: review and commit the changes.", file=stdout)
