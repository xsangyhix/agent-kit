"""Helpers that give each guardrail test its own throwaway git repository.

Nothing here mocks git or imports the scripts under test: a test writes files
into a temporary repo, stages them, and runs the real script as a subprocess.
That is the same path the pre-commit hook takes.
"""

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CHECKER = REPO_ROOT / "src" / "agent_kit" / "payload" / "kit" / "check_tracker.py"
HOOK = REPO_ROOT / "src" / "agent_kit" / "payload" / "kit" / "hooks" / "pre-commit"

# The marker names the hook treats as an agent session. They must be cleared
# from every test's environment, because the test run itself may be an agent
# session, and then set again only for the cases that call for them.
AI_MARKERS = ("AI_AGENT", "OPENCODE")


def _run(command, cwd, env=None):
    return subprocess.run(
        command,
        cwd=str(cwd),
        env=env,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )


def find_shell():
    """Return a POSIX shell, or None.

    The hook is `sh`. Prefer one on PATH; on Windows, Git for Windows ships
    `sh.exe`, so fall back to the Git installation itself. The hook cannot run
    without a shell, so a test skips only when neither source yields one.
    """
    for name in ("sh", "bash"):
        found = shutil.which(name)
        if found:
            return found

    git = shutil.which("git")
    if not git:
        return None

    exec_path = _run([git, "--exec-path"], cwd=REPO_ROOT).stdout.strip()
    if not exec_path:
        return None

    # .../mingw64/libexec/git-core -> .../Git
    git_root = Path(exec_path).parents[2]
    for candidate in (
        git_root / "usr" / "bin" / "sh.exe",
        git_root / "bin" / "bash.exe",
    ):
        if candidate.exists():
            return str(candidate)
    return None


class GitRepo:
    """A temporary git repository with a checked-out branch."""

    def __init__(self, branch="agent/test"):
        self._temporary = tempfile.TemporaryDirectory()
        self.root = Path(self._temporary.name)
        self.git("init", "-q")
        self.git("config", "user.email", "guardrail@example.com")
        self.git("config", "user.name", "Guardrail Test")
        self.git("config", "core.autocrlf", "false")
        self.git("checkout", "-q", "-b", branch)

    def close(self):
        self._temporary.cleanup()

    def git(self, *args):
        result = _run(["git", *args], cwd=self.root)
        if result.returncode != 0:
            raise AssertionError(
                "git {} failed:\n{}\n{}".format(
                    " ".join(args), result.stdout, result.stderr
                )
            )
        return result

    def write(self, relative, content):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            path.write_bytes(content)
        else:
            path.write_text(content, encoding="utf-8")
        return path

    def stage(self, *paths):
        self.git("add", "--", *paths)

    def commit(self, message="fixture"):
        self.git("commit", "-q", "-m", message)

    def run_checker(self):
        return _run([sys.executable, str(CHECKER)], cwd=self.root)

    def add_hook_fixtures(self):
        """Stub the pieces the hook runs, so only the hook is under test."""
        self.write(".agents/kit/check_tracker.py", "raise SystemExit(0)\n")
        self.write(
            ".agents/kit/harness.sh",
            "# Generated by agent-kit. Do not edit; run `agent-kit update` instead.\n"
            'AGENT_MARKERS="AI_AGENT OPENCODE"\n',
        )

    def run_hook(self, shell, markers=(), clear_markers=()):
        """Run the hook with the agent markers removed from the environment.

        The test run may itself be an agent session, so the default markers are
        always cleared first, along with any extra names the case uses, and
        then set again only where the case calls for them.
        """
        removed = set(AI_MARKERS) | set(clear_markers)
        env = {key: value for key, value in os.environ.items() if key not in removed}
        for marker in markers:
            env[marker] = "1"
        # Git prepends its own bin folders to PATH when it runs a hook, so the
        # hook's `sh` call resolves. A test launches the hook directly, so give
        # it the same reach by putting the shell's folder on PATH.
        env["PATH"] = str(Path(shell).parent) + os.pathsep + env.get("PATH", "")
        return _run([shell, str(HOOK)], cwd=self.root, env=env)
