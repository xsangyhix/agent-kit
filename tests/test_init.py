SKILLS_PAYLOAD = PAYLOAD / "skills"
TEMPLATES = PAYLOAD / "templates"

BEGIN = "<!-- agent-kit:begin -->"
END = "<!-- agent-kit:end -->"
PLACEHOLDER = "{{KIT_BLOCK}}"
HARNESS_SH = (
    "# Generated by agent-kit. Do not edit; run `agent-kit update` instead.\n"
    'AGENT_MARKERS="AI_AGENT OPENCODE"\n'
)
GITATTRIBUTES_LINE = ".agents/kit/hooks/* text eol=lf"

TEMPLATE_NAMES = ("AGENTS.md", "GLOSSARY.md", "docs/agents/project.md")


class InitTests(unittest.TestCase):
    def setUp(self):
        self.repo = GitRepo()
        self.addCleanup(self.repo.close)
        self.root = self.repo.root

    def run_init(self, path=None, harness=None, force=False, stdin=None, payload=None):
        stdout = io.StringIO()
        stderr = io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            code = installer.init(
                path or self.root,
                harness,
                force,
                stdin or FakeStdin(),
                stdout,
                payload=payload,
            )
        return code, stdout.getvalue(), stderr.getvalue()

    def install(self, **kwargs):
        code, stdout, stderr = self.run_init(**kwargs)
        self.assertEqual(code, 0, stdout + stderr)
        self.assertEqual(stderr, "")
        return stdout

    def assert_nothing_written(self):
        self.assertFalse((self.root / ".agents" / "kit").exists())
        self.assertFalse((self.root / ".agents" / "kit.lock").exists())
        self.assertFalse((self.root / ".gitattributes").exists())

    # -- the fresh install -------------------------------------------------

    def test_fresh_repo_installs_the_kit_and_the_skills_byte_for_byte(self):
        self.install()

        for source in sorted(KIT_PAYLOAD.rglob("*")):
            if not source.is_file():
                continue
            target = self.root / ".agents" / "kit" / source.relative_to(KIT_PAYLOAD)
            with self.subTest(source=source):
                self.assertTrue(target.is_file(), target)
                self.assertEqual(target.read_bytes(), source.read_bytes())

        for source in sorted(SKILLS_PAYLOAD.rglob("*")):
            if not source.is_file():
                continue
            target = (
                self.root / ".agents" / "skills" / source.relative_to(SKILLS_PAYLOAD)
            )
            with self.subTest(source=source):
                self.assertTrue(target.is_file(), target)
                self.assertEqual(target.read_bytes(), source.read_bytes())

    def test_fresh_repo_does_not_copy_bytecode_caches(self):
        payload = copied_payload(self)
        cache = payload / "kit" / "__pycache__"
        cache.mkdir()
        (cache / "check_tracker.cpython-314.pyc").write_bytes(b"cache\n")
        (payload / "kit" / "stray.pyc").write_bytes(b"cache\n")

        self.install(payload=payload)

        self.assertFalse((self.root / ".agents/kit/__pycache__").exists())
        self.assertFalse((self.root / ".agents/kit/stray.pyc").exists())
        self.assertNotIn(
            ".agents/kit/__pycache__/check_tracker.cpython-314.pyc",
            lock_data(self.root)["files"],
        )

    def test_fresh_repo_writes_the_harness_file(self):
        self.install()

        harness = self.root / ".agents" / "kit" / "harness.sh"
        self.assertEqual(harness.read_bytes(), HARNESS_SH.encode("utf-8"))

    def test_fresh_repo_creates_the_project_templates(self):
        self.install()

        for name in TEMPLATE_NAMES:
            with self.subTest(name=name):
                self.assertTrue((self.root / name).is_file(), name)

        self.assertEqual(
            (self.root / "GLOSSARY.md").read_bytes(),
            (TEMPLATES / "GLOSSARY.md").read_bytes(),
        )
        self.assertEqual(
            (self.root / "docs" / "agents" / "project.md").read_bytes(),
            (TEMPLATES / "docs" / "agents" / "project.md").read_bytes(),
        )

    def test_fresh_repo_fills_the_kit_block(self):
        self.install()

        text = read_text(self.root / "AGENTS.md")
        self.assertNotIn(PLACEHOLDER, text)
        self.assertEqual(text.count(BEGIN), 1)
        self.assertEqual(text.count(END), 1)
        self.assertIn("{}\n{}\n{}".format(BEGIN, block_content(), END), text)

    def test_fresh_repo_creates_the_tracker_placeholders(self):
        self.install()

        for relative in ("docs/adr/.gitkeep", ".scratch/.gitkeep"):
            with self.subTest(relative=relative):
                path = self.root / relative
                self.assertTrue(path.is_file(), relative)
                self.assertEqual(path.read_bytes(), b"")

    def test_fresh_repo_appends_the_gitattributes_line(self):
        self.install()

        text = read_text(self.root / ".gitattributes")
        self.assertEqual(text, GITATTRIBUTES_LINE + "\n")

    def test_fresh_repo_points_core_hooks_path_at_the_kit(self):
        self.install()

        result = subprocess.run(
            ["git", "-C", str(self.root), "config", "core.hooksPath"],
            capture_output=True,
            text=True,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout.strip(), ".agents/kit/hooks")

    def test_the_lock_lists_every_kit_file_with_its_hash(self):
        self.install()

        expected = {}
        for source in sorted(KIT_PAYLOAD.rglob("*")):
            if source.is_file():
                relative = source.relative_to(KIT_PAYLOAD).as_posix()
                expected[".agents/kit/" + relative] = sha256_file(source)
        for source in sorted(SKILLS_PAYLOAD.rglob("*")):
            if source.is_file():
                relative = source.relative_to(SKILLS_PAYLOAD).as_posix()
                expected[".agents/skills/" + relative] = sha256_file(source)
        expected[".agents/kit/harness.sh"] = sha256_text(HARNESS_SH)

        data = lock_data(self.root)
        self.assertEqual(data["files"], expected)

    def test_the_lock_records_the_version_harness_and_block_hash(self):
        self.install()

        data = lock_data(self.root)
        self.assertEqual(data["kit_version"], "0.1.0")
        self.assertEqual(data["harness"], "opencode")
        self.assertEqual(data["agents_block"], sha256_text(block_content() + "\n"))

    def test_the_lock_is_sorted_two_space_json_with_a_trailing_newline(self):
        self.install()

        raw = (self.root / ".agents" / "kit.lock").read_bytes().decode("utf-8")
        data = json.loads(raw)
        self.assertTrue(raw.endswith("\n"))
        self.assertEqual(raw, json.dumps(data, indent=2, sort_keys=True) + "\n")

    def test_the_summary_reports_the_install(self):
        stdout = self.install()

        self.assertIn("agent-kit 0.1.0", stdout)
        self.assertIn("opencode", stdout)
        self.assertIn("Created:", stdout)
        self.assertIn("Kit block:", stdout)
        self.assertIn("Next: review and commit the changes.", stdout)

